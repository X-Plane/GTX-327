    end
    draw_center(small, title, center, 6, true, emit_run)

    if render.page == 0 then
        if not render.pressure_altitude_valid then
            draw_center(small, "NO ALT", center, 20, true, emit_run)
            return
        end
        local prefix = tostring(render.pressure_prefix or "")
        local value = tostring(render.pressure_value or "")
        local suffix = tostring(render.pressure_suffix or "")
        local prefix_gap = prefix ~= "" and 2 or 0
        local stacked_feet = suffix == "ft"
        local suffix_width = stacked_feet and 10 or text_width(small, suffix)
        local suffix_gap = suffix ~= "" and 2 or 0
        local total = text_width(small, prefix) + prefix_gap
            + text_width(medium, value) + suffix_gap + suffix_width
        -- centred like Garmin's FL page; wide feet / meter values keep a
        -- 2-dot gap before the trend arrow column (x 191)
        local x = math.min(math.floor(center - total / 2), 189 - total)
        x = draw_text(small, prefix, x, 22, true, emit_run) + prefix_gap
        x = draw_text(medium, value, x, 18, true, emit_run) + suffix_gap
        if stacked_feet then
            -- Reference display places the unit letters diagonally: f at the
            -- upper-left and t at the lower-right of one compact suffix cell.
            draw_text(small, "f", x, 18, true, emit_run)
            draw_text(small, "t", x + 4, 23, true, emit_run)
        else
            draw_text(small, suffix, x, 22, true, emit_run)
        end
        if render.altitude_trend ~= 0 then
            local name = render.altitude_trend > 0 and "trend_up_" or "trend_down_"
            name = name .. (math.abs(render.altitude_trend) == 2 and "large" or "small")
            emit_mask(M.symbols[name], 191, math.abs(render.altitude_trend) == 2 and 18 or 20, true, emit_run)
        end
    elseif render.page == 1 then
        draw_medium_value(render.flight_time_text or format_hms(render.flight_time), center, 18, nil, emit_run)
    elseif render.page == 2 then
        draw_medium_value(render.count_up_text or format_hms(render.count_up_elapsed), center, 18, nil, emit_run)
    elseif render.page == 3 then
        local cursor = render.count_down_entry_active
            and timer_cursor_character(render.count_down_entry_cursor_position)
            or nil
        local text = render.count_down_text or render.count_down_entry_text or format_hms(render.count_down_value)
        draw_medium_value(text, center, 18, cursor, emit_run)
    elseif render.page == 4 or render.page == 5 then
        local level = render.page == 4 and render.contrast_level or render.display_level
        draw_bar(center - 31, 18, level, emit_run)
    end
end

-- Installer configuration pages (IM Rev N 5.2), laid out by gtx327_setup.lua.
-- An item is { font = "small" or "bold", text, x, y [, highlight, cursor] },
-- { bar = level, x, y } or { symbol = name, x, y }. A highlighted field is
-- inverse video with one dot of margin (as pictured in IM 5.2.5); cursor = n highlights
-- only character n while a number is being typed.
local function draw_setup(items, emit_run)
    for _, item in ipairs(items) do
        if item.bar ~= nil then
            draw_bar(item.x, item.y, item.bar, emit_run)
        elseif item.symbol ~= nil then
            emit_mask(M.symbols[item.symbol], item.x, item.y, true, emit_run)
        else
            local font = M.fonts[item.font]
            local text = tostring(item.text or "")
            if item.highlight and item.cursor == nil then
                emit_run(item.x - 1, item.y - 1, text_width(font, text) + 1, font.height + 2, true)
            end
            local x = item.x
            for index = 1, string.len(text) do
                local spec = glyph_for(font, string.sub(text, index, index))
                if item.highlight and item.cursor == index then
                    emit_run(x - 1, item.y - 1, spec.advance + 1, font.height + 2, true)
                end
                local inverse = item.highlight and (item.cursor == nil or item.cursor == index)
                emit_mask(spec, x, item.y, not inverse, emit_run)
                x = x + spec.advance
            end
        end
    end
end

function M.draw_screen(render, emit_run)
    if render == nil or not render.powered then return end
    local small = M.fonts.small

    if render.power_state == 1 then
        -- Real unit at power-up: every dot lit for about a second before the
        -- start-up page (bench video, GTX 327 SW 2.09).
        if not render.self_test_text_visible then
            emit_run(0, 0, 200, 33, true)
            return
        end
        local micro = M.fonts.micro
        local title = "XPNDR 327"
        local year = "1999-2026"
        local title_width = text_width(small, title) * 2
        local mark_width = M.symbols.copyright.advance
        local year_width = text_width(small, year)
        local line_width = title_width + 3 + mark_width + 2 + year_width
        local x = math.floor((200 - line_width) / 2)
        draw_text_resampled(small, title, x, 1, 2, 1.5, true, emit_run)
        x = x + title_width + 3
        emit_mask(M.symbols.copyright, x, 4, true, emit_run)
        draw_text(small, year, x + mark_width + 2, 4, true, emit_run)

        local version = "SW Ver. v12 X-Plane by Laminar Research"
        draw_center(micro, version, 100, 14, true, emit_run)
        -- Pilot's guide wording for an internal failure found by the self test.
        local status = render.self_test_failed and "SELF TEST FAILED" or "Self Test In Progress"
        draw_center(small, status, 100, 24, true, emit_run)
        return
    end

    if render.power_state == 3 then
        -- configuration mode: OFF still shows the power-down message
        if render.shutdown_message then
            draw_function_zone(render, emit_run)
        else
            draw_setup(render.setup_items or {}, emit_run)
        end
        return
    end

    draw_code(render, emit_run)
    draw_text(small, render.mode_text or "", 2, 12, true, emit_run)
    if render.ident then draw_text(small, "IDENT", 0, 1, true, emit_run) end
    if render.reply then emit_mask(M.symbols.reply, 2, 22, true, emit_run) end
    draw_function_zone(render, emit_run)

    -- Debug state remains available through datarefs; the authentic LCD is not
    -- contaminated with a heartbeat overlay.
end

function M.measure(style, text)
    local font = M.fonts[style]
    return font ~= nil and text_width(font, text) or 0
end

