    return ({ 1, 2, 4, 5, 7, 8 })[digit]
end

local function draw_medium_value(text, center_x, y, cursor_character, emit_run)
    local font = M.fonts.medium
    local x = math.floor(center_x - text_width(font, text) / 2)
    text = tostring(text or "")
    for index = 1, string.len(text) do
        local spec = glyph_for(font, string.sub(text, index, index))
        if cursor_character == index then
            -- one dot of margin on every side, as the configuration-page
            -- cursor (draw_setup): the inverted digit is closed on the right
            emit_run(x - 1, y - 1, spec.advance + 1, 14, true)
            emit_mask(spec, x, y, false, emit_run)
        else
            emit_mask(spec, x, y, true, emit_run)
        end
        x = x + spec.advance
    end
end

local function draw_code(render, emit_run)
    local font = M.fonts.large
    local text = tostring(render.code_text or "0000")
    local x = 42
    local cursor_slot = nil
    if render.code_entry_active then
        cursor_slot = math.min(math.max(math.floor(
            render.code_entry_cursor_slot or render.code_entry_count or 1
        ), 1), 4)
    end
    for index = 1, 4 do
        local spec = glyph_for(font, string.sub(text, index, index))
        if cursor_slot == index then
            -- Cursor block (as pictured in the pilot's guide, p4): 19 x 27
            -- from one column into the 18-dot slot; the digit inside sits one
            -- column right of its normal place (the p4 picture's 1 against
            -- Figure 5-1's).
            emit_run(x + 1, 3, 19, 27, true)
            emit_mask(spec, x + 1, 3, false, emit_run)
        else
            emit_mask(spec, x, 3, true, emit_run)
        end
        x = x + 18
    end
end

