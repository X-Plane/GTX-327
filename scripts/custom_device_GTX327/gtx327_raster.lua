local function glyph_for(font, character)
    local exact = font.glyphs[character]
    if exact ~= nil then return exact end
    return font.glyphs[string.upper(character)] or font.glyphs[" "]
end

local function emit_mask(spec, x, y, on, emit_run)
    if spec == nil then return end
    for row_index = 1, #spec.rows do
        local line = spec.rows[row_index]
        local run_start = nil
        for column = 1, string.len(line) + 1 do
            local set = column <= string.len(line) and string.sub(line, column, column) == "1"
            if set and run_start == nil then
                run_start = column
            elseif not set and run_start ~= nil then
                emit_run(x + run_start - 1, y + row_index - 1, column - run_start, 1, on)
                run_start = nil
            end
        end
    end
end

local function text_width(font, text)
    local width = 0
    text = tostring(text or "")
    for index = 1, string.len(text) do
        width = width + glyph_for(font, string.sub(text, index, index)).advance
    end
    return width
end

local function draw_text(font, text, x, y, on, emit_run)
    local cursor = x
    text = tostring(text or "")
    for index = 1, string.len(text) do
        local spec = glyph_for(font, string.sub(text, index, index))
        emit_mask(spec, cursor, y, on, emit_run)
        cursor = cursor + spec.advance
    end
    return cursor
end

local function emit_mask_scaled(spec, x, y, scale_x, scale_y, on, emit_run)
    if spec == nil then return end
    for row_index = 1, #spec.rows do
        local line = spec.rows[row_index]
        local run_start = nil
        for column = 1, string.len(line) + 1 do
            local set = column <= string.len(line) and string.sub(line, column, column) == "1"
            if set and run_start == nil then
                run_start = column
            elseif not set and run_start ~= nil then
                emit_run(
                    x + (run_start - 1) * scale_x,
                    y + (row_index - 1) * scale_y,
                    (column - run_start) * scale_x,
                    scale_y,
                    on
                )
                run_start = nil
            end
        end
    end
end

local function emit_mask_resampled(spec, x, y, scale_x, scale_y, on, emit_run)
    if spec == nil then return end
    for row_index = 1, #spec.rows do
        local line = spec.rows[row_index]
        local run_start = nil
        for column = 1, string.len(line) + 1 do
            local set = column <= string.len(line) and string.sub(line, column, column) == "1"
            if set and run_start == nil then
                run_start = column
            elseif not set and run_start ~= nil then
                local left = math.floor(x + (run_start - 1) * scale_x + 0.5)
                local right = math.floor(x + (column - 1) * scale_x + 0.5)
                local top = math.floor(y + (row_index - 1) * scale_y + 0.5)
                local bottom = math.floor(y + row_index * scale_y + 0.5)
                if right > left and bottom > top then
                    emit_run(left, top, right - left, bottom - top, on)
                end
                run_start = nil
            end
        end
    end
end

local function draw_text_resampled(font, text, x, y, scale_x, scale_y, on, emit_run)
    local source_cursor = 0
    text = tostring(text or "")
    for index = 1, string.len(text) do
        local spec = glyph_for(font, string.sub(text, index, index))
        emit_mask_resampled(spec, x + source_cursor * scale_x, y, scale_x, scale_y, on, emit_run)
        source_cursor = source_cursor + spec.advance
    end
    return math.floor(x + source_cursor * scale_x + 0.5)
end

local function draw_center_scaled(font, text, center_x, y, scale_x, scale_y, on, emit_run)
    local width = text_width(font, text) * scale_x
    local x = math.floor(center_x - width / 2)
    text = tostring(text or "")
    for index = 1, string.len(text) do
        local spec = glyph_for(font, string.sub(text, index, index))
        emit_mask_scaled(spec, x, y, scale_x, scale_y, on, emit_run)
        x = x + spec.advance * scale_x
    end
end

local function draw_center(font, text, center_x, y, on, emit_run)
    return draw_text(font, text, math.floor(center_x - text_width(font, text) / 2), y, on, emit_run)
end

local function draw_right(font, text, right_x, y, on, emit_run)
    return draw_text(font, text, right_x - text_width(font, text), y, on, emit_run)
end

local function format_hms(seconds)
    local total = math.max(0, math.min(math.floor(tonumber(seconds) or 0), 359999))
    return string.format("%02d:%02d:%02d", math.floor(total / 3600), math.floor(total / 60) % 60, total % 60)
end

